-- Dominio archivos
CREATE TABLE archivos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  propietario_id INTEGER NOT NULL,
  proposito archivos_proposito_enum NOT NULL,
  storage_bucket VARCHAR(100) NOT NULL,
  proveedor VARCHAR(20) NOT NULL DEFAULT 'local',
  extension VARCHAR(12) NOT NULL,
  ancho_px INTEGER NULL,
  alto_px INTEGER NULL,
  storage_key VARCHAR(500) NOT NULL,
  nombre_original VARCHAR(255) NOT NULL,
  mime_detectado VARCHAR(120) NOT NULL,
  tamano_bytes BIGINT NOT NULL,
  sha256 BYTEA NOT NULL,
  estado archivos_estado_enum NOT NULL DEFAULT 'cargando',
  escaneo archivos_escaneo_enum NOT NULL DEFAULT 'pendiente',
  procesamiento archivos_procesamiento_enum NOT NULL DEFAULT 'no_aplica',
  duracion_segundos INTEGER NULL,
  eliminado_en TIMESTAMPTZ NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_archivo_objeto UNIQUE (storage_bucket, storage_key),
  CONSTRAINT uq_archivo_propietario UNIQUE (id, propietario_id),
  CONSTRAINT fk_archivo_usuario FOREIGN KEY (propietario_id) REFERENCES usuarios (id),
  CONSTRAINT ck_archivo_tamano CHECK (tamano_bytes > 0),
  CONSTRAINT ck_archivos_sha256_bytes CHECK (octet_length(sha256) = 32),
  CONSTRAINT ck_archivo_proveedor CHECK (proveedor IN ('local','s3')),
  CONSTRAINT ck_archivo_dimensiones CHECK ((ancho_px IS NULL OR ancho_px > 0) AND (alto_px IS NULL OR alto_px > 0)),
  CONSTRAINT ck_archivos_id_no_negativo CHECK (id >= 0),
  CONSTRAINT ck_archivos_tamano_bytes_no_negativo CHECK (tamano_bytes >= 0),
  CONSTRAINT ck_archivos_duracion_segundos_no_negativo CHECK (duracion_segundos >= 0)
);

