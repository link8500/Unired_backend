-- actualizado_en se mantiene también al actualizar por SQL.
CREATE FUNCTION actualizar_timestamp() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.actualizado_en = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;
