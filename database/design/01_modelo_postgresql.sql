-- Dominio tutorias
CREATE TABLE tutorias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  tutor_id INTEGER NOT NULL,
  area_id INTEGER NOT NULL,
  habilitacion_id BIGINT NULL,
  titulo VARCHAR(220) NOT NULL,
  descripcion TEXT NOT NULL,
  nivel tutorias_nivel_enum NOT NULL DEFAULT 'todos',
  modalidad tutorias_modalidad_enum NOT NULL DEFAULT 'grabada',
  estado tutorias_estado_enum NOT NULL DEFAULT 'borrador',
  precio_base DECIMAL(12,2) NOT NULL DEFAULT 0,
  descuento_porcentaje DECIMAL(5,2) NOT NULL DEFAULT 0,
  moneda CHAR(3) NOT NULL DEFAULT 'NIO',
  portada_archivo_id BIGINT NULL,
  version_lock INTEGER NOT NULL DEFAULT 1,
  publicada_en TIMESTAMPTZ NULL,
  eliminada_en TIMESTAMPTZ NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_tutoria_tutor UNIQUE (id, tutor_id),
  CONSTRAINT fk_tutoria_usuario FOREIGN KEY (tutor_id) REFERENCES usuarios (id),
  CONSTRAINT fk_tutoria_area FOREIGN KEY (area_id) REFERENCES areas_tutoria (id),
  CONSTRAINT fk_tutoria_habilitacion FOREIGN KEY (habilitacion_id, tutor_id, area_id) REFERENCES habilitaciones_tutor (id, tutor_id, area_id),
  CONSTRAINT fk_tutoria_portada FOREIGN KEY (portada_archivo_id, tutor_id) REFERENCES archivos (id, propietario_id),
  CONSTRAINT ck_tutoria_publicacion CHECK (estado <> 'publicada' OR (habilitacion_id IS NOT NULL AND publicada_en IS NOT NULL)),
  CONSTRAINT ck_tutoria_precio CHECK (precio_base >= 0 AND descuento_porcentaje BETWEEN 0 AND 90 AND (precio_base > 0 OR descuento_porcentaje = 0)),
  CONSTRAINT ck_tutorias_id_no_negativo CHECK (id >= 0),
  CONSTRAINT ck_tutorias_habilitacion_id_no_negativo CHECK (habilitacion_id >= 0),
  CONSTRAINT ck_tutorias_portada_archivo_id_no_negativo CHECK (portada_archivo_id >= 0),
  CONSTRAINT ck_tutorias_version_lock_no_negativo CHECK (version_lock >= 0)
);

