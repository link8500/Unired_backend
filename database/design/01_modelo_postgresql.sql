  tipo_precio anuncios_market_tipo_precio_enum NOT NULL DEFAULT 'negociable',
  precio_base DECIMAL(12,2) NULL,
  descuento_porcentaje DECIMAL(5,2) NOT NULL DEFAULT 0,
