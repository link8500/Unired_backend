-- Dominio usuarios
CREATE TABLE usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(180) NOT NULL,
  email VARCHAR(254) NOT NULL,
  edad SMALLINT NULL,
  estado usuarios_estado_enum NOT NULL DEFAULT 'pendiente_email',
  email_verificado_en TIMESTAMPTZ NULL,
  eliminado_en TIMESTAMPTZ NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_usuario_email UNIQUE (email),
  CONSTRAINT ck_usuario_edad CHECK (edad IS NULL OR edad BETWEEN 0 AND 130),
  CONSTRAINT ck_usuario_email_normalizado CHECK (email = lower(btrim(email)))
);

-- Dominio roles
CREATE TABLE roles (
  codigo VARCHAR(32) NOT NULL,
  nombre VARCHAR(80) NOT NULL,
  PRIMARY KEY (codigo)
);

-- Dominio usuario_roles
